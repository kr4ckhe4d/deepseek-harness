/**
 * Generate the desktop application's backend closure manifest.
 *
 * The packaged application ships a deployed `node_modules` rather than the
 * checkout, and `pnpm deploy --prod` resolves only what the deploy root
 * declares. Harness packages name `@deepseek-ai/cordis` and its plugins as
 * peer dependencies, which a production deploy does not supply on their
 * behalf, so the deploy root must name every workspace package the web
 * profile reaches — over dependencies AND peer dependencies, transitively.
 *
 * Run: `pnpm run gen-desktop-runtime-closure`.
 */
import { globSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const MANIFEST = 'apps/desktop/runtime/package.json'

/**
 * The packages the desktop backend boots: the launcher plus the two bundles
 * the packaged web profile names.
 */
const ROOTS = [
  '@deepseek-ai/dsh',
  '@deepseek-ai/dsh-base',
  '@deepseek-ai/dsh-web-app',
] as const

interface Manifest {
  name?: string
  dependencies?: Record<string, string>
  peerDependencies?: Record<string, string>
}

/**
 * Index every workspace package by name.
 *
 * @returns each package's dependency and peer-dependency names by package name.
 */
function workspacePackages(): Map<string, readonly string[]> {
  const patterns = [
    'packages/*/*/package.json',
    'vendor/*/package.json',
    'apps/*/package.json',
    'native/landlock-run/package.json',
    'native/landlock-run/packages/*/package.json',
  ]
  const byName = new Map<string, readonly string[]>()
  for (const pattern of patterns) {
    for (const relative of globSync(pattern, { cwd: ROOT })) {
      const manifest = JSON.parse(readFileSync(join(ROOT, relative), 'utf8')) as Manifest
      if (manifest.name === undefined) continue
      byName.set(manifest.name, [
        ...Object.keys(manifest.dependencies ?? {}),
        ...Object.keys(manifest.peerDependencies ?? {}),
      ])
    }
  }
  return byName
}

/**
 * Walk the workspace graph from {@link ROOTS}.
 *
 * @param byName - the workspace index.
 * @returns every reachable workspace package name.
 */
function closureOf(byName: Map<string, readonly string[]>): string[] {
  const reached = new Set<string>()
  const pending: string[] = [...ROOTS]
  while (pending.length > 0) {
    const name = pending.pop()
    if (name === undefined || reached.has(name)) continue
    const edges = byName.get(name)
    if (edges === undefined) continue
    reached.add(name)
    for (const edge of edges) if (byName.has(edge)) pending.push(edge)
  }
  return [...reached].sort()
}

const names = closureOf(workspacePackages())
const manifest = {
  name: 'dsh-desktop-runtime-closure',
  description:
    'Dependency-only deploy root defining the backend the packaged desktop application runs. '
    + 'Generated by scripts/gen-desktop-runtime-closure.ts; do not edit by hand.',
  version: '0.0.1',
  private: true,
  type: 'module',
  dependencies: Object.fromEntries(names.map(name => [name, 'workspace:^'])),
}
writeFileSync(join(ROOT, MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`)
console.log(`gen-desktop-runtime-closure: wrote ${MANIFEST} (${String(names.length)} packages).`)
